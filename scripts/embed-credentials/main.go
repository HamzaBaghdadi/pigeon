// Command embed-credentials writes the release OAuth client into a gitignored
// Go file so official builds can offer "Sign in with Google" out of the box.
//
// It reads PIGEON_GOOGLE_CLIENT_ID and PIGEON_GOOGLE_CLIENT_SECRET from the
// environment (GitHub Actions secrets in CI) and never prints them. If
// PIGEON_VERSION is set (the release tag, e.g. v0.2.0) it also stamps the app
// version into internal/version/release_version.go.
//
//	go run ./scripts/embed-credentials          # write services/release_credentials.go
//	go run ./scripts/embed-credentials -clean   # remove it again
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const (
	out        = "services/release_credentials.go"
	versionOut = "internal/version/release_version.go"
)

func main() {
	clean := flag.Bool("clean", false, "remove the generated file")
	flag.Parse()

	if *clean {
		for _, f := range []string{out, versionOut} {
			if err := os.Remove(f); err != nil && !os.IsNotExist(err) {
				fail(err)
			}
		}
		fmt.Println("removed generated release files")
		return
	}

	id := strings.TrimSpace(os.Getenv("PIGEON_GOOGLE_CLIENT_ID"))
	secret := strings.TrimSpace(os.Getenv("PIGEON_GOOGLE_CLIENT_SECRET"))
	if id == "" || secret == "" {
		fail(fmt.Errorf("PIGEON_GOOGLE_CLIENT_ID and PIGEON_GOOGLE_CLIENT_SECRET must both be set"))
	}
	if !strings.HasSuffix(id, ".apps.googleusercontent.com") {
		fail(fmt.Errorf("PIGEON_GOOGLE_CLIENT_ID doesn't look like a Google client ID"))
	}

	src := fmt.Sprintf(`// Code generated by scripts/embed-credentials. DO NOT EDIT. DO NOT COMMIT.

package services

func init() {
	GoogleClientID = %q
	GoogleClientSecret = %q
}
`, id, secret)
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		fail(err)
	}
	if err := os.WriteFile(out, []byte(src), 0o600); err != nil {
		fail(err)
	}
	fmt.Println("wrote", out, "(values hidden)")

	if v := strings.TrimPrefix(strings.TrimSpace(os.Getenv("PIGEON_VERSION")), "v"); v != "" {
		if !validVersion(v) {
			fail(fmt.Errorf("PIGEON_VERSION %q isn't a version like v1.2.3", v))
		}
		src := fmt.Sprintf("// Code generated by scripts/embed-credentials. DO NOT EDIT. DO NOT COMMIT.\n\npackage version\n\nfunc init() { Version = %q }\n", v)
		if err := os.WriteFile(versionOut, []byte(src), 0o644); err != nil {
			fail(err)
		}
		fmt.Println("wrote", versionOut, "version", v)
	}
}

func validVersion(v string) bool {
	core := strings.SplitN(v, "-", 2)[0]
	parts := strings.Split(core, ".")
	if len(parts) != 3 {
		return false
	}
	for _, p := range parts {
		if p == "" || strings.Trim(p, "0123456789") != "" {
			return false
		}
	}
	return true
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "embed-credentials:", err)
	os.Exit(1)
}
